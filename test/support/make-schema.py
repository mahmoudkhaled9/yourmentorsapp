#!/usr/bin/env python3
"""Regenerates test/support/schema.sqlite.sql: the REAL production table layout taken from backups/mentors_crm_portable.sql
(structure only - no data is copied). Text columns get COLLATE NOCASE to approximate MySQL's utf8mb4_0900_ai_ci.
Run: python3 test/support/make-schema.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = (root / 'backups' / 'mentors_crm_portable.sql').read_text(encoding='utf-8', errors='replace')
tables = re.findall(r'CREATE TABLE `(\w+)` \((.*?)\n\) ENGINE', src, flags=re.S)
out = ['-- AUTO-GENERATED by make-schema.py from the production backup (structure only). Test fixture.', 'PRAGMA foreign_keys = ON;']
idx = []
for name, body in tables:
    cols, extras, pk, auto = [], [], None, set()
    for l in [x.strip().rstrip(',') for x in body.strip().split('\n')]:
        m = re.match(r'`(\w+)` (\w+)(?:\(([\d, ]+)\))?(.*)$', l)
        if m:
            c, t, args, rest = m.groups(); t = t.lower()
            if 'AUTO_INCREMENT' in rest: auto.add(c)
            st = {'int': 'INTEGER', 'integer': 'INTEGER', 'bigint': 'INTEGER', 'smallint': 'INTEGER', 'tinyint': 'TINYINT(1)',
                  'varchar': f'VARCHAR({args}) COLLATE NOCASE', 'text': 'TEXT COLLATE NOCASE', 'longtext': 'TEXT COLLATE NOCASE', 'mediumtext': 'TEXT COLLATE NOCASE',
                  'decimal': f'DECIMAL({(args or "").replace(" ", "")})', 'timestamp': 'TIMESTAMP', 'datetime': 'TIMESTAMP', 'date': 'DATE'}.get(t, t.upper())
            parts = [f'`{c}`', st]
            if 'NOT NULL' in rest: parts.append('NOT NULL')
            d = re.search(r"DEFAULT (NULL|'[^']*'|[\w.]+)", rest)
            if d and d.group(1) != 'NULL': parts.append('DEFAULT ' + d.group(1))
            cols.append(' '.join(parts)); continue
        if l.startswith('PRIMARY KEY'): pk = re.search(r'\(`(\w+)`\)', l).group(1); continue
        m = re.match(r'UNIQUE KEY `(\w+)` \((.*)\)', l)
        if m: extras.append(f'UNIQUE ({m.group(2)})'); continue
        m = re.match(r'KEY `(\w+)` \((.*)\)', l)
        if m: idx.append(f'CREATE INDEX IF NOT EXISTS `{name}_{m.group(1)}` ON `{name}` ({m.group(2)});'); continue
        m = re.match(r'CONSTRAINT `\w+` FOREIGN KEY \((.*?)\) REFERENCES `(\w+)` \((.*?)\)(.*)$', l)
        if m: extras.append(f'FOREIGN KEY ({m.group(1)}) REFERENCES `{m.group(2)}` ({m.group(3)}){m.group(4)}')
    if pk:
        for i, c in enumerate(cols):
            if c.startswith(f'`{pk}` INTEGER'):
                cols[i] = f'`{pk}` INTEGER PRIMARY KEY' + (' AUTOINCREMENT' if pk in auto else ' NOT NULL'); break
    out.append(f'CREATE TABLE `{name}` (\n  ' + ',\n  '.join(cols + extras) + '\n);')
(root / 'test' / 'support' / 'schema.sqlite.sql').write_text('\n'.join(out + idx) + '\n', encoding='utf-8')
print(f'wrote schema.sqlite.sql with {len(tables)} tables')
